package com.shilian.web.dto;

/**
 * 给一条<b>已存记录</b>重跑分析的请求。
 *
 * <p>刻意不复用 {@link AnalyzeRequest}：那个要求 {@code url} 必填，
 * 而这里的网址从记录里读。让前端回传网址，就等于给了它改这条记录身份的机会——
 * 虽然是自己用的工具，但「身份字段只能由服务端定」这条线还是该守住，
 * 否则将来某次前端笔误就会把一条记录指到别的网址上。
 */
public record ReanalyzeRequest(
        /**
         * 可选。用户粘贴的页面正文。
         *
         * <p>为空表示「重新抓一次」——抓取失败常常是暂时的（对方站点当时在抽风），
         * 过几天再试可能就好了。带上它则跳过抓取，直接用贴进来的内容分析。
         */
        String text
) {
}
